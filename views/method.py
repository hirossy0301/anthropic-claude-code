"""「予測の仕組み」の画面。数値は docs/spec.html と同じ (3年分のバックテストの結果)。"""
import streamlit as st

st.title("予測の仕組み")
st.caption("このアプリが確率をどう出しているか、どのくらい当たるかをまとめています。")

st.markdown("""
### このアプリでできること
- 各艇の **1着確率** と、**3連単120通りの確率**（上位を表示）
- **1マークの展開予想**：どの艇が、逃げ・差し・まくり・まくり差しのどれで勝つか
- **単勝の期待値**：ボタンを押すと、そのレースの単勝オッズを取得して「1着確率 × オッズ」を表示

### 使っているデータ
- ボートレース公式の **番組表**（出走表）と **競走成績**。直近3年分です。毎朝6時17分と9時17分に自動で更新します。
- 気温は Open-Meteo（気象データ）から、場ごと・締切時刻ごとの値を使います。
- 単勝オッズは、ボタンを押したときに公式サイトから1回だけ取得します。
""")

st.markdown("### 1着確率の出し方")
st.markdown("""
過去のレースから「どんな条件の艇が1着になったか」を、**LightGBM**（決定木をたくさん組み合わせる機械学習の手法）で学習します。
1艇ずつ「1着になりそうな度合い」を出し、**レース内の6艇で合計100%になるように割り振ります**。
""")
c1, c2 = st.columns(2)
with c1:
    st.markdown("""
**朝の予想**（前日までに分かる情報）
- 級別、全国・当地の勝率と2連率
- モーター・ボートの2連率
- 選手の平均スタートタイミング（前日まで）
- 選手の枠ごとの1着率、場ごとの枠の1着率
- 場×コースの1着率、水面（海・川・湖）と水質、体重差
- 気温
""")
with c2:
    st.markdown("""
**直前の予想**（朝の情報に加えて）
- 進入コース（前付けなど）
- 風向・風速、波高
- 展示タイム（レース内の平均との差・順位）

「直前情報を取得」ボタンで、公式の直前情報から自動で入れられます。
展示タイムを入れると、展示タイムも使うモデルに切り替わります
（直近1年の検証で 1着的中率 +0.42%、これまでに加えた要因で一番の改善）。

直前情報は公式サイトの直前情報を見て入力します。
結果が出ているレースには、実際の値が最初から入っています。
""")
st.markdown("""
**リーク防止**：選手の成績などの履歴は、**そのレースの前日までのデータだけ**で計算しています。
当日以降の結果が混ざると、検証で実力以上に良く見えてしまうためです。

**枠ごとの補正**：検証すると、モデルは「強い1号艇はもっと勝ち、弱い1号艇はもっと負ける」ことを小さく見積もっていました。
そこで枠ごとに補正をかけています（1号艇の差を約1.5倍に広げる）。
""")

st.markdown("### 3連単の確率")
st.markdown("""
1着確率から、「1着が決まったら、残りの艇の中から2着を、さらに残りから3着を選ぶ」という順番で掛け合わせます。

**例**：1号艇 50%、2号艇 20%、3号艇 10% のとき

1-2-3 の確率 = 50% × (20% ÷ 残り50%) × (10% ÷ 残り30%) ≈ **6.7%**

この方法は2着・3着の確率に偏りが出やすいことが知られています。
""")

st.markdown("### 1マークの展開予想（決まり手）")
st.markdown("""
公式データには **1マーク通過時の順位が記録されていません**。そこで、成績に記録されている **決まり手** で1マークの展開を表しています。

| 決まり手 | 意味 |
|---|---|
| 逃げ | 1コースの艇が1マークを先に回ってそのまま勝つ |
| 差し | 内側の艇が回るのを待ち、その内側を抜けて勝つ |
| まくり | 外から内側の艇をまとめて追い越して勝つ |
| まくり差し | 外から一気に内に切り込み、間を抜けて勝つ |
| 抜き | 1マークの後で前の艇を抜いて勝つ |
| 恵まれ | 前の艇の失格などで勝つ |

「艇 i が決まり手 k で勝つ確率」= **1着確率 × 勝ったときにその決まり手になる確率** として計算します。
後ろの確率は、進入コース、その艇と内側・外側の艇のスタートの速さ、1コースの艇の強さ、選手ごとの過去の決まり手の割合（逃げ率・まくり率など）から学習しています。
「1マークで先頭」は、逃げ・差し・まくり・まくり差しのどれかでその艇が勝つ確率です。

検証（直近1年 54,339レース）では、勝った艇が分かっているときの決まり手の的中率は 77.6% で、
「場×コースの決まり手の割合」だけを使う場合（76.4%）より良くなりました。
特に効いているのは、進入コースと、**1つ内側の艇のスタートの速さと勝率**です。
""")

st.markdown("### どのくらい当たるか")
st.markdown("""
2023年10月〜2025年9月で学習し、**その後1年分（54,339レース）** で確かめた結果です（学習に使っていない期間で検証）。

| 予想 | 1着的中率 | 3連単 上位5点の的中率 | 3連単 上位5点の回収率 |
|---|---|---|---|
| 場×枠の1着率だけ（比較用） | 55.0% | 25.3% | 73.7% |
| 朝の予想 | 56.8% | 31.6% | 76.6% |
| 直前の予想 | 57.1% | 32.0% | 78.9% |

- 1着的中率 = 1着確率が一番高い艇が、実際に1着だった割合
- 回収率は控除率（約25%）の分を取り返せておらず、**どの四半期も75〜78%** でした
- 直前の予想が良くなるのは、主に進入コースの情報によるものです
""")

st.markdown("### 注意")
st.markdown("""
- 確率は過去データからの統計的な推定です。**的中や利益を保証するものではありません。**
- 公式サイトの情報は私的使用に限られています。取得したオッズを他の人に配ったり、転載したりしないでください。
- 24場の水面の分類（海・川・湖）は、まだ公式の情報と照合していません。
""")
